def page(path: str, title: str, description: str, body: str, root: str) -> None:
    html = f"""<!DOCTYPE html>
<html lang="ja">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} - {APP}</title>
  <meta name="description" content="{description}">
  <link rel="stylesheet" href="{root}style.css">
  <!-- tool_build.py で作るファイル。直すときは tool_build.py を直して作り直す -->
</head>
<body>
<main>
  <header><a href="{root}">{APP}</a></header>
{body}
  <footer>
    <nav>
      <a href="{root}">サポート</a>
      <a href="{root}terms/">利用規約</a>
      <a href="{root}privacy/">プライバシーポリシー</a>
      <a href="{root}tokushoho/">特定商取引法に基づく表記</a>
    </nav>
  </footer>
</main>
</body>
</html>
"""
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html)


